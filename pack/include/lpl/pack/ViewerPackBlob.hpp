/**
 * @file ViewerPackBlob.hpp
 * @brief The world viewer's cartridge, as bytes, for a boot with no slot.
 *
 * The image lpl::editor::bakeGamePack() produces from
 * `assets/games/worldview.lplscene`: a 64x64 world with a town, roads, caves and
 * four scatter rules, plus the ecosystem declared on it.
 *
 * It exists for one specific failure, and the failure was observed rather than
 * imagined. The graphical profile prefers a `world.lplpak` GRUB module, and the
 * workflow that publishes the browser demo builds its ISOs on a runner carrying
 * the cross toolchain but no xmake — so no `lpl-bake`, so no cartridge baked, so
 * no module in the image, so the kernel fell back to the PARITY pack. The
 * published demo showed a 24x24 test world and nothing was broken anywhere:
 * every layer did exactly what it says it does.
 *
 * So the fallback is the demo world rather than the gate's. Checked in for the
 * same reason ParityPackBlob.hpp is — the kernel build must need no host tool —
 * and guarded the same way: test-game-pack asserts these bytes still match what
 * the baker produces, so a stale blob fails a test rather than quietly shipping
 * last month's world.
 *
 * @author MasterLaplace
 * @version 0.1.0
 * @copyright MIT License
 */

