/**
 * @file ParityPackBlob.hpp
 * @brief A reference cartridge, as bytes, for the cross-target parity gate.
 *
 * The image lpl::editor::bakeGamePack() produces from
 * lpl::procgen::parityWorldRecipe(). It exists so the kernel can exercise the
 * REAL pack reader on REAL bytes without yet having a transport: this is the
 * cartridge, minus the slot.
 *
 * The bytes are checked in rather than generated at build time so the kernel
 * build needs no host tool. That trade would normally invite drift, so the host
 * test test-game-pack asserts these bytes still equal what the baker produces
 * today — a stale blob fails a test rather than silently validating an old
 * world.
 *
 * Refresh it — do NOT hand-edit the array:
 *
 *     lpl-bake --header kParityPackBytes - pack/include/lpl/pack/ParityPackBlob.hpp
 *
 * The `-` means "the parity recipe", which comes from code rather than from a
 * document. That is exactly what makes it the reference.
 *
 * @author MasterLaplace
 * @version 0.1.0
 * @copyright MIT License
 */

